package reports;

import static org.junit.jupiter.api.Assertions.assertDoesNotThrow;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.TreeMap;
import org.junit.jupiter.api.Test;

/**
 * Public tests for the order reports. Every failure message starts with its task number.
 * Each database test gets its own fresh H2 in-memory database, loaded from ../fixtures/orders.sql
 * and gone as soon as its connection closes. Do not edit this file.
 */
class OrderReportsTest {

    private static int databases;

    private static Connection freshDatabase() throws SQLException {
        databases++;
        return DriverManager.getConnection(
                "jdbc:h2:mem:lab" + databases + ";INIT=RUNSCRIPT FROM '../fixtures/orders.sql'");
    }

    /** The twelve fixture rows as records, so the stream tasks can be tested without Task 1. */
    private static final List<Order> FIXTURE = List.of(
            new Order("A-101", "ana", "north", "SHIPPED", 800),
            new Order("A-102", "bo", "south", "OPEN", 990),
            new Order("A-103", "cyd", "north", "OPEN", 15000),
            new Order("A-104", "ana", "north", "OPEN", 450),
            new Order("A-105", "dee", "east", "CANCELLED", 300),
            new Order("A-106", "bo", "south", "OPEN", 12500),
            new Order("A-107", "eli", "east", "SHIPPED", 2200),
            new Order("A-108", "ana", "north", "OPEN", 9000),
            new Order("A-109", "cyd", "north", "CANCELLED", 20000),
            new Order("A-110", "fay", "west", "OPEN", 3000),
            new Order("A-111", "bo", "south", "SHIPPED", 600),
            new Order("A-112", "eli", "east", "OPEN", 10000));

    /** The fixture in a scrambled order, so sorting is really tested. */
    private static List<Order> scrambled() {
        List<Order> list = new ArrayList<>();
        for (int i = 0; i < FIXTURE.size(); i++) {
            list.add(FIXTURE.get((i * 5) % FIXTURE.size()));
        }
        return list;
    }

    private static List<String> codesWhere(java.util.function.Predicate<Order> rule) {
        List<String> codes = new ArrayList<>();
        for (Order o : FIXTURE) {
            if (rule.test(o)) {
                codes.add(o.code());
            }
        }
        return codes;
    }

    @Test
    void task1LoadAllRowsIntoRecords() throws SQLException {
        try (Connection connection = freshDatabase()) {
            List<Order> rows = OrderLoader.loadAll(connection);
            assertEquals(12, rows.size(), "Task 1: loadAll must return one Order per row of the orders table (12 rows)");
            assertEquals(FIXTURE, rows, "Task 1: loadAll must read code, customer, region, status and cents into each Order, in code order");
        }
    }

    @Test
    void task2RulesFromLambdasAndCombinators() {
        assertEquals(List.of("A-103", "A-106", "A-109", "A-112"), codesWhere(OrderReports.IS_LARGE),
                "Task 2: IS_LARGE must be true for orders of 10000 cents or more");
        assertEquals(List.of("A-103", "A-106", "A-112"), codesWhere(OrderReports.NEEDS_REVIEW),
                "Task 2: NEEDS_REVIEW must be true only for orders that are open AND large");
        assertEquals(10, codesWhere(OrderReports.ACTIVE).size(),
                "Task 2: ACTIVE must be true for the 10 orders that are not cancelled");
        assertFalse(OrderReports.ACTIVE.test(FIXTURE.get(4)), "Task 2: ACTIVE must be false for the cancelled order A-105");
        assertEquals("NORTH", OrderReports.REGION_TAG.apply(FIXTURE.get(0)), "Task 2: REGION_TAG of a north order must be NORTH");
        assertEquals("WEST", OrderReports.REGION_TAG.apply(FIXTURE.get(9)), "Task 2: REGION_TAG of a west order must be WEST");
        assertEquals(List.of("A-103", "A-106", "A-109", "A-112"), codesWhere(OrderReports.largeFor(false)),
                "Task 2: largeFor(false) must be true from 10000 cents, like IS_LARGE");
        assertEquals(List.of("A-103", "A-106", "A-108", "A-109", "A-112"), codesWhere(OrderReports.largeFor(true)),
                "Task 2: largeFor(true) must be true from 5000 cents for VIP customers");
    }

    @Test
    void task3OpenCodesSorted() {
        List<Order> input = scrambled();
        List<Order> before = List.copyOf(input);
        assertEquals(List.of("A-102", "A-103", "A-104", "A-106", "A-108", "A-110", "A-112"), OrderReports.openCodes(input),
                "Task 3: openCodes must keep only OPEN orders, map them to their codes and sort the codes");
        assertEquals(before, input, "Task 3: openCodes must not change the caller's list");
        assertEquals(List.of(), OrderReports.openCodes(List.of()), "Task 3: openCodes of no orders must be an empty list");
    }

    @Test
    void task4OpenSummaryUsesEachStreamOnce() {
        List<Order> two = List.of(FIXTURE.get(3), FIXTURE.get(0), FIXTURE.get(1));
        String[] summary = new String[1];
        assertDoesNotThrow(() -> summary[0] = OrderReports.openSummary(two),
                "Task 4: openSummary must not reuse a stream after its terminal operation (IllegalStateException)");
        assertEquals("2 open: A-102, A-104", summary[0], "Task 4: openSummary of A-104, A-101 and A-102");
        assertEquals("0 open: ", OrderReports.openSummary(List.of()), "Task 4: openSummary of no orders");
    }

    @Test
    void task5GroupAndCount() {
        assertEquals(new TreeMap<>(Map.of("OPEN", 7L, "SHIPPED", 3L, "CANCELLED", 2L)), new TreeMap<>(OrderReports.countByStatus(FIXTURE)),
                "Task 5: countByStatus must count the orders of each status (counting() gives Long values)");
        assertEquals(new TreeMap<>(Map.of(
                        "north", List.of("A-101", "A-103", "A-104", "A-108", "A-109"),
                        "south", List.of("A-102", "A-106", "A-111"),
                        "east", List.of("A-105", "A-107", "A-112"),
                        "west", List.of("A-110"))),
                new TreeMap<>(OrderReports.codesByRegion(FIXTURE)),
                "Task 5: codesByRegion must map each region to its order codes, in input order");
    }

    @Test
    void task6TotalsWhenKeysRepeat() {
        Map<String, Integer>[] totals = new Map[1];
        assertDoesNotThrow(() -> totals[0] = OrderReports.centsByCustomer(FIXTURE),
                "Task 6: centsByCustomer must not throw on a customer with several orders; give toMap a merge function");
        assertEquals(new TreeMap<>(Map.of("ana", 10250, "bo", 14090, "cyd", 35000, "dee", 300, "eli", 12200, "fay", 3000)), new TreeMap<>(totals[0]),
                "Task 6: centsByCustomer must add up every order of each customer");
    }

    @Test
    void task7OptionalWithoutGet() {
        assertEquals("A-103", OrderReports.largestOpenCode(FIXTURE),
                "Task 7: largestOpenCode must return the code of the open order with the most cents");
        String[] code = new String[1];
        assertDoesNotThrow(() -> code[0] = OrderReports.largestOpenCode(List.of(FIXTURE.get(0), FIXTURE.get(4))),
                "Task 7: largestOpenCode must not throw when no order is open; do not call get() on an empty Optional");
        assertEquals("none", code[0], "Task 7: largestOpenCode must return \"none\" when no order is open");
        assertEquals("none", OrderReports.largestOpenCode(List.of()), "Task 7: largestOpenCode of no orders must be \"none\"");
    }

    @Test
    void task8OpenTotalsReducedInSql() throws SQLException {
        String sql = OrderLoader.OPEN_TOTALS_SQL.toUpperCase(Locale.ROOT).replaceAll("\\s+", " ");
        assertTrue(sql.contains("WHERE") && sql.contains("GROUP BY") && sql.contains("HAVING"),
                "Task 8 (static check of the query text): OPEN_TOTALS_SQL must reduce in SQL with WHERE, GROUP BY and HAVING");
        try (Connection connection = freshDatabase()) {
            Map<String, Integer> above = OrderLoader.openTotalsAbove(connection, 10000);
            assertEquals(new TreeMap<>(Map.of("bo", 13490, "cyd", 15000)), new TreeMap<>(above),
                    "Task 8: open totals above 10000 cents must be bo 13490 and cyd 15000 (eli's 10000 is not above)");
            assertEquals(List.of("bo", "cyd"), new ArrayList<>(above.keySet()), "Task 8: customers must come A to Z (ORDER BY)");
            assertEquals(List.of("ana", "bo", "cyd", "eli"),
                    new ArrayList<>(OrderLoader.openTotalsAbove(connection, 5000).keySet()),
                    "Task 8: with a 5000-cent minimum, ana, bo, cyd and eli qualify, in that order");
        }
    }
}
